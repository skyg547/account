    @ParameterizedTest
    @CsvSource({"DRAFT, 2026-05-31", "POSTED, 2026-07-31"})
    void inactiveMalformedValuationDoesNotBlockEligibleBalances(String status, LocalDate accountingDate)
            throws Exception {
        originalBalance("11000", "USD", "DEBIT", "100.00", "1000.00");
        valueAt(MAY_END, 11L, "12");
        jdbc.update("""
                UPDATE journal_entries SET lineage_source_id = 'unattributable', status = ?, accounting_date = ?
                 WHERE id = ?
                """, status, Date.valueOf(accountingDate), journals.entryIds.get(0));

        assertOnlyBalance(JUNE_END, "11000", "USD", "100.00", "1000.00");
        var reader = source.createReader(JUNE_END, "KRW", "11000", "11000", 10);
        reader.open(new ExecutionContext());
        try {
            assertBalance(reader.read(), "11000", "USD", "100.00", "1000.00");
            assertThat(reader.read()).isNull();
        } finally {
            reader.close();
        }
    }

    private void assertInvalidLineageAtBothEntryPoints() {
        assertThatThrownBy(() -> source.createPartitions(JUNE_END, "KRW", 4))
                .isInstanceOf(IllegalStateException.class).hasMessageContaining("FX valuation lineage");
        // A restarted worker can open its saved range without calling the partitioner again.
        var reader = source.createReader(JUNE_END, "KRW", "11000", "11000", 10);
        assertThatThrownBy(() -> {
            reader.open(new ExecutionContext());
            try {
                while (reader.read() != null) {
                    // Invalid roots must be rejected even when they sort after ordinary balances.
                }
            } finally {
                reader.close();
            }
        }).isInstanceOf(IllegalStateException.class).hasMessageContaining("FX valuation lineage");
    }

    private void valueAt(LocalDate date, long batchId, String rate) throws Exception {
        valueAt(date, batchId, Map.of("USD", rate, "EUR", rate));
    }

    private void valueAt(LocalDate date, long batchId, Map<String, String> rates) throws Exception {
        var service = serviceAt(rates);
        for (FxValuationBalance balance : readAt(date)) {
            service.processFxValuationForAccount(balance, date, batchId);
        }
    }

    private FxValuationService serviceAt(Map<String, String> rates) {
        return new FxValuationService((from, to, requestedDate) -> {
            assertThat(to).isEqualTo("KRW");
            return Optional.ofNullable(rates.get(from)).map(BigDecimal::new);
        }, journals, properties, masterData);
    }

    private void assertOnlyBalance(LocalDate date, String account, String currency, String principal, String book)
            throws Exception {
        assertThat(readAt(date)).singleElement().satisfies(balance ->
                assertBalance(balance, account, currency, principal, book));
    }

    private void assertBalance(FxValuationBalance balance, String account, String currency,
                               String principal, String book) {
        assertThat(balance).isNotNull();
        assertThat(balance.accountCode()).isEqualTo(account);
        assertThat(balance.currencyCode()).isEqualTo(currency);
        assertThat(balance.foreignEndingBalance()).isEqualByComparingTo(principal);
        assertThat(balance.bookReportingAmount()).isEqualByComparingTo(book);
    }

    private void assertAdjustment(int index, String lineage, ClosingJournalSide side, String amount) {
        ClosingJournalEntryCommand command = journals.commands.get(index);
        assertThat(command.lineageSourceType()).isEqualTo("FX_VALUATION");
        assertThat(command.lineageSourceId()).isEqualTo(lineage);
        assertThat(command.currencyCode()).isEqualTo("KRW");
        assertThat(command.entryType()).isEqualTo("CLOSING_ADJUSTMENT");
        assertThat(command.lines()).hasSize(2);
        assertThat(command.lines().get(0).accountCode()).isEqualTo(lineage.split("\\|")[1]);
        assertThat(command.lines().get(0).side()).isEqualTo(side);
        assertThat(command.lines().get(1).side()).isNotEqualTo(side);
        assertThat(command.lines().get(1).accountCode())
                .isEqualTo(side == ClosingJournalSide.DEBIT ? "72000" : "92000");
        assertThat(command.lines()).allSatisfy(detail -> {
            assertThat(detail.amount()).isEqualByComparingTo(amount);
            assertThat(detail.baseAmount()).isEqualByComparingTo(amount);
        });
    }

    private List<FxValuationBalance> readAt(LocalDate date) throws Exception {
        List<FxValuationBalance> balances = new ArrayList<>();
        for (ExecutionContext range : source.createPartitions(date, "KRW", 4).values()) {
            var reader = source.createReader(date, "KRW", range.getString("startAccountCode"),
                    range.getString("endAccountCode"), 10);
            reader.open(new ExecutionContext());
            try {
                FxValuationBalance balance;
                while ((balance = reader.read()) != null) {
                    balances.add(balance);
                }
            } finally {
                reader.close();
            }
        }
        return balances;
    }

    private long originalBalance(String account, String currency, String side, String amount, String baseAmount) {
        long id = journals.nextId++;
        jdbc.update("""
                INSERT INTO journal_entries
                    (id, status, accounting_date, currency_code, entry_type)
                VALUES (?, 'POSTED', DATE '2026-05-01', ?, 'NORMAL')
                """, id, currency);
        line(id, account, side, new BigDecimal(amount), new BigDecimal(baseAmount));
        return id;
    }

    private long reverse(long originalId, LocalDate date, String status) {
        long id = journals.nextId++;
        // Mirror the real reversal contract: reference the immediate source and keep it POSTED.
        jdbc.update("""
                INSERT INTO journal_entries
                    (id, status, accounting_date, currency_code, entry_type, lineage_source_type, lineage_source_id)
                SELECT ?, ?, ?, currency_code, 'REVERSAL', 'JOURNAL_ENTRY', ?
                  FROM journal_entries WHERE id = ?
                """, id, status, Date.valueOf(date), Long.toString(originalId), originalId);
        jdbc.update("""
                INSERT INTO journal_details (journal_entry_id, account_code, side, amount, base_amount)
                SELECT ?, account_code, CASE WHEN side = 'DEBIT' THEN 'CREDIT' ELSE 'DEBIT' END, amount, base_amount
                  FROM journal_details WHERE journal_entry_id = ?
                """, id, originalId);
        return id;
    }

    private void line(long entryId, String account, String side, BigDecimal amount, BigDecimal baseAmount) {
        jdbc.update("""
                INSERT INTO journal_details (journal_entry_id, account_code, side, amount, base_amount)
                VALUES (?, ?, ?, ?, ?)
                """, entryId, account, side, amount, baseAmount);
    }

    private final class PersistedJournalPort implements ClosingJournalEntryPort {
        private long nextId = 1;
        private final List<ClosingJournalEntryCommand> commands = new ArrayList<>();
        private final List<Long> entryIds = new ArrayList<>();

        @Override
        public ClosingJournalEntryResult createDraftAdjustment(ClosingJournalEntryCommand command) {
            long id = nextId++;
            commands.add(command);
            entryIds.add(id);
            jdbc.update("""
                    INSERT INTO journal_entries
                        (id, status, accounting_date, currency_code, entry_type, lineage_source_type, lineage_source_id)
                    VALUES (?, 'DRAFT', ?, ?, ?, ?, ?)
                    """, id, Date.valueOf(command.accountingDate()), command.currencyCode(), command.entryType(),
                    command.lineageSourceType(), command.lineageSourceId());
            command.lines().forEach(detail -> line(id, detail.accountCode(), detail.side().name(),
                    detail.amount(), detail.baseAmount()));
            return new ClosingJournalEntryResult(id, command.slipNo());
        }

        @Override
        public void approveAndPost(Long journalEntryId, String actor) {
            jdbc.update("UPDATE journal_entries SET status = 'POSTED' WHERE id = ?", journalEntryId);
        }
    }
