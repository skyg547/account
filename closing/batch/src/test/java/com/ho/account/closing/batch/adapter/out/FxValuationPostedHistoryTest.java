    @Test
    void draftRetryReproducesSameCommandAndSlipWhilePostedRetryCreatesNothing() throws Exception {
        originalBalance("11000", "USD", "DEBIT", "100.00", "1000.00");
        properties.setAutoPostAdjustments(false);
        valueAt(MAY_END, 11L, "12");
        valueAt(MAY_END, 11L, "12");

        // The synthetic port records both requests; Journal's own duplicate handling is tested elsewhere.
        assertThat(journals.commands).hasSize(2);
        assertThat(journals.commands.get(1)).isEqualTo(journals.commands.get(0));
        journals.approveAndPost(journals.entryIds.get(0), "SYSTEM");
        properties.setAutoPostAdjustments(true);
        valueAt(MAY_END, 11L, "12");
        assertThat(journals.commands).hasSize(2);
        assertOnlyBalance(MAY_END, "11000", "USD", "100.00", "1200.00");
    }

    @Test
    void cursorRestartResumesInStableAccountAndSourceCurrencyOrder() throws Exception {
        originalBalance("12000", "USD", "DEBIT", "100.00", "1000.00");
        originalBalance("11000", "USD", "DEBIT", "100.00", "1000.00");
        originalBalance("11000", "EUR", "DEBIT", "100.00", "1000.00");
        valueAt(MAY_END, 11L, "12");
        ExecutionContext checkpoint = new ExecutionContext();
        var reader = source.createReader(JUNE_END, "KRW", "11000", "12000", 2);
        reader.open(checkpoint);
        try {
            assertBalance(reader.read(), "11000", "EUR", "100.00", "1200.00");
            reader.update(checkpoint);
        } finally {
            reader.close();
        }

        var restarted = source.createReader(JUNE_END, "KRW", "11000", "12000", 2);
        restarted.open(checkpoint);
        try {
            assertBalance(restarted.read(), "11000", "USD", "100.00", "1200.00");
            assertBalance(restarted.read(), "12000", "USD", "100.00", "1200.00");
            assertThat(restarted.read()).isNull();
        } finally {
            restarted.close();
        }
    }

