import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

/** Real source/mapping adapters with synthetic H2 storage behind the remote Journal contract. */
final class EclJournalFixture {
    static final LocalDate DATE = LocalDate.of(2026, 5, 31);
    final JdbcTemplate jdbc;
    final JournalPostingPort posting = mock(JournalPostingPort.class);
    final JournalQueryPort query = mock(JournalQueryPort.class);
    final ExchangeRateQueryPort rates = mock(ExchangeRateQueryPort.class);
    final ClosingAccountingProperties properties = new ClosingAccountingProperties();
    final FxValuationEligibilityResolver eligibility = mock(FxValuationEligibilityResolver.class);
    final GlAllowanceBalanceLookupAdapter balances;
    final List<JournalEntryCommand> commands = new ArrayList<>();
    final EclProvisionService service;
    private long nextId = 1;

    EclJournalFixture() {
        var dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:ecl-units-" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE journal_entries (
                    id BIGINT PRIMARY KEY, status VARCHAR(20), accounting_date DATE, slip_date DATE,
                    currency_code VARCHAR(3), exchange_rate NUMERIC(19,8), entry_type VARCHAR(50),
                    lineage_source_type VARCHAR(50), lineage_source_id VARCHAR(100),
                    slip_no VARCHAR(20), description VARCHAR(255))
                """);
        jdbc.execute("""
                CREATE TABLE journal_details (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    journal_entry_id BIGINT, account_code VARCHAR(50), side VARCHAR(10),
                    amount NUMERIC(19,2), base_amount NUMERIC(19,2), description VARCHAR(255))
                """);
        // Keep the old read model present: a passing result must come from posted amounts, not its base total.
        jdbc.execute("""
                CREATE TABLE gl_balances (account_code VARCHAR(50), currency_code VARCHAR(3),
                    balance_date DATE, period VARCHAR(7), ending_balance NUMERIC(19,2))
                """);
        jdbc.execute("""
                CREATE TABLE allowance_summary (
                    base_date DATE, run_id VARCHAR(80), model_version VARCHAR(80), legal_entity_code VARCHAR(20),
                    currency_code VARCHAR(3), exposure_account_code VARCHAR(20), allowance_account_code VARCHAR(20),
                    bad_debt_expense_account_code VARCHAR(20), reversal_income_account_code VARCHAR(20),
                    target_allowance_amount NUMERIC(19,4), source_exposure_amount NUMERIC(19,4),
                    stage1_allowance_amount NUMERIC(19,4), stage2_allowance_amount NUMERIC(19,4),
                    stage3_allowance_amount NUMERIC(19,4))
                """);
        var rule = new ClosingAccountingProperties.AutomatedJournalRule();
        rule.setDebitAccountCode("550100");
        rule.setCreditAccountCode("129100");
        rule.setAmount(BigDecimal.ONE);
        properties.getProvisionRules().put(ProvisionBatch.ProvisionType.ECL, rule);
        balances = new GlAllowanceBalanceLookupAdapter(
                new JournalFxValuationBalanceSource(dataSource, jdbc, eligibility));
        service = new EclProvisionService(balances,
                new JournalLedgerClosingJournalEntryAdapter(posting, query), properties,
                new JdbcEclAllowanceResultAdapter(jdbc), new MasterDataFxExchangeRateLookupAdapter(rates));
        when(query.findBySlipNo(anyString())).thenAnswer(invocation -> jdbc.query(
                "SELECT * FROM journal_entries WHERE slip_no = ?", (rs, row) -> {
                    JournalSummary result = new JournalSummary();
                    result.setId(rs.getLong("id"));
                    result.setStatus(rs.getString("status"));
                    result.setAccountingDate(rs.getDate("accounting_date").toLocalDate());
                    result.setSlipDate(rs.getDate("slip_date").toLocalDate());
                    result.setCurrencyCode(rs.getString("currency_code"));
                    result.setEntryType(rs.getString("entry_type"));
                    result.setLineageSourceType(rs.getString("lineage_source_type"));
                    result.setLineageSourceId(rs.getString("lineage_source_id"));
                    result.setSlipNo(rs.getString("slip_no"));
                    result.setDescription(rs.getString("description"));
                    return result;
                }, new Object[]{invocation.getArgument(0)}).stream().findFirst());
        when(query.getJournalDetails(anyLong())).thenAnswer(invocation -> jdbc.query(
                "SELECT * FROM journal_details WHERE journal_entry_id = ?", (rs, row) -> {
                    var result = new JournalDetailSummary();
                    result.setAccountCode(rs.getString("account_code"));
                    result.setSide(JournalSide.valueOf(rs.getString("side")));
                    result.setAmount(rs.getBigDecimal("amount"));
                    result.setBaseAmount(rs.getBigDecimal("base_amount"));
                    result.setDetailDescription(rs.getString("description"));
                    return result;
                }, new Object[]{invocation.getArgument(0)}));
        when(posting.createDraftEntry(any())).thenAnswer(invocation -> persist(invocation.getArgument(0)));
        doAnswer(invocation -> {
            jdbc.update("UPDATE journal_entries SET status = 'POSTED' WHERE id = ?",
                    new Object[]{invocation.getArgument(0)});
            return null;
        }).when(posting).approveAndPost(anyLong(), anyString());
    }

    void target(String currency, String target) {
        jdbc.update("""
                INSERT INTO allowance_summary VALUES (?, 'RUN-781', 'MODEL-781', 'SYNTHETIC', ?,
                    '12000', '129100', '550100', '480100', ?, 10000, ?, 0, 0)
                """, DATE, currency, decimal(target), decimal(target));
    }

    void replaceTarget(String currency, String target) {
        jdbc.update("UPDATE allowance_summary SET target_allowance_amount = ? WHERE currency_code = ?",
                decimal(target), currency);
    }

    void rate(String from, String to, String value) {
        when(rates.findLatestRateAt(from, to, DATE)).thenReturn(
                Optional.of(new ExchangeRateRef(from, to, decimal(value), DATE)));
    }

    long ordinary(String status, LocalDate date, String currency, String account,
                  String side, String transaction, String base) {
        long id = entry(status, date, currency, "NORMAL", null, null);
        line(id, account, side, transaction, base);
        line(id, "550100", opposite(side), transaction, base);
        return id;
    }

    long fx(String status, LocalDate date, String functionalCurrency, String lineage,
            String account, String side, String base) {
        long id = entry(status, date, functionalCurrency, "CLOSING_ADJUSTMENT", "FX_VALUATION", lineage);
        line(id, account, side, base, base);
        line(id, "72000", opposite(side), base, base);
        return id;
    }

    long reverse(long originalId, String status, LocalDate date) {
        long id = nextId++;
        jdbc.update("""
                INSERT INTO journal_entries (id, status, accounting_date, currency_code, entry_type,
                                             lineage_source_type, lineage_source_id)
                SELECT ?, ?, ?, currency_code, 'REVERSAL', 'JOURNAL_ENTRY', ?
                FROM journal_entries WHERE id = ?
                """, id, status, date, Long.toString(originalId), originalId);
        jdbc.update("""
                INSERT INTO journal_details (journal_entry_id, account_code, side, amount, base_amount)
                SELECT ?, account_code, CASE WHEN side = 'DEBIT' THEN 'CREDIT' ELSE 'DEBIT' END, amount, base_amount
                FROM journal_details WHERE journal_entry_id = ?
                """, id, originalId);
        return id;
    }

    JournalPostingResult persist(JournalEntryCommand command) {
        long id = nextId++;
        commands.add(command);
        // Exact conversion prevents the test store from silently hiding a production precision error.
        jdbc.update("""
                INSERT INTO journal_entries VALUES (?, 'DRAFT', ?, ?, ?, ?, ?, ?, ?, ?, ?)
                """, id, command.accountingDate(), command.slipDate(), command.currencyCode(),
                command.exchangeRate().setScale(8, RoundingMode.UNNECESSARY), command.entryType(),
                command.lineageSourceType(), command.lineageSourceId(), command.slipNo(), command.description());
        command.lines().forEach(line -> jdbc.update("""
                INSERT INTO journal_details (journal_entry_id, account_code, side, amount, base_amount, description)
                VALUES (?, ?, ?, ?, ?, ?)
                """, id, line.accountCode(), line.drcrType(), line.amount().setScale(2, RoundingMode.UNNECESSARY),
                line.baseAmount().setScale(2, RoundingMode.UNNECESSARY), line.detailDescription()));
        return new JournalPostingResult(id, command.slipNo(), "DRAFT");
    }

    private long entry(String status, LocalDate date, String currency, String type, String source, String lineage) {
        long id = nextId++;
        jdbc.update("""
                INSERT INTO journal_entries (id, status, accounting_date, currency_code, entry_type,
                                             lineage_source_type, lineage_source_id) VALUES (?, ?, ?, ?, ?, ?, ?)
                """, id, status, date, currency, type, source, lineage);
        return id;
    }

    private void line(long entryId, String account, String side, String amount, String base) {
        jdbc.update("""
                INSERT INTO journal_details (journal_entry_id, account_code, side, amount, base_amount)
                VALUES (?, ?, ?, ?, ?)
                """, entryId, account, side, decimal(amount), decimal(base));
    }

    private static String opposite(String side) {
        return "CREDIT".equals(side) ? "DEBIT" : "CREDIT";
    }

    static BigDecimal decimal(String value) {
        return new BigDecimal(value);
    }
}
