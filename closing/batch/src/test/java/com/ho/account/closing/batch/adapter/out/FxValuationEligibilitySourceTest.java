import static org.mockito.Mockito.*;

/** Real source SQL and shared core policy with synthetic complete journals; no provider services. */
class FxValuationEligibilitySourceTest {
    private static final LocalDate DATE = LocalDate.of(2026, 5, 31);
    private JdbcTemplate jdbc;
    private JournalFxValuationBalanceSource source;
    private ClosingAccountingProperties properties;
    private MasterDataQueryPort metadata;
    private FxValuationEligibilityResolver resolver;
    private long nextId;

    @BeforeEach
    void setUp() {
        var dataSource = new DriverManagerDataSource(
                "jdbc:h2:mem:closing-fx-eligibility-" + System.nanoTime() + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE journal_entries (
                    id BIGINT PRIMARY KEY, status VARCHAR(20) NOT NULL,
                    accounting_date DATE NOT NULL, currency_code VARCHAR(3) NOT NULL,
                    entry_type VARCHAR(50) DEFAULT 'NORMAL' NOT NULL,
                    lineage_source_type VARCHAR(50), lineage_source_id VARCHAR(100))
                """);
        jdbc.execute("""
                CREATE TABLE journal_details (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    journal_entry_id BIGINT NOT NULL, account_code VARCHAR(50) NOT NULL,
                    side VARCHAR(10) NOT NULL, amount DECIMAL(19,2) NOT NULL, base_amount DECIMAL(19,2) NOT NULL)
                """);
        properties = new ClosingAccountingProperties();
        properties.setFxValuationReportingCurrencyCode("USD");
        metadata = mock(MasterDataQueryPort.class);
        resolver = new FxValuationEligibilityResolver(properties, metadata);
        source = new JournalFxValuationBalanceSource(dataSource, jdbc, resolver);
    }

    @ParameterizedTest
    @CsvSource({"REVENUE,false,CREDIT,DEBIT,72000", "EXPENSES,false,DEBIT,CREDIT,92000",
            "ASSETS,true,DEBIT,CREDIT,92000", "ASSETS,false,DEBIT,CREDIT,92000"})
    void completeForeignJournalProducesOnlyEligibleMonetaryAdjustment(
            String historicalCategory, boolean fixedAsset, String historicalSide,
            ClosingJournalSide monetarySide, String pnlAccount) throws Exception {
        configure("11000", monetarySide == ClosingJournalSide.DEBIT ? "ASSETS" : "LIABILITIES", false, MONETARY);
        configure("41000", historicalCategory, fixedAsset, HISTORICAL_COST);
        long entry = entry("EUR");
        line(entry, "11000", monetarySide.name());
        line(entry, "41000", historicalSide);

        var balances = partitionedBalances();
        assertThat(balances).singleElement().satisfies(balance -> {
            assertThat(balance.accountCode()).isEqualTo("11000");
            assertThat(balance.foreignEndingBalance()).isEqualByComparingTo(
                    monetarySide == ClosingJournalSide.DEBIT ? "100" : "-100");
        });
        var commands = new ArrayList<ClosingJournalEntryCommand>();
        var journals = mock(ClosingJournalEntryPort.class);
        when(journals.createDraftAdjustment(any())).thenAnswer(invocation -> {
            commands.add(invocation.getArgument(0));
            return new ClosingJournalEntryResult(1L, "FX");
        });
        var service = new FxValuationService((from, to, date) -> Optional.of(new BigDecimal("1.2")),
                journals, properties, resolver);
        balances.forEach(balance -> service.processFxValuationForAccount(balance, DATE, 780L));
        assertThat(commands).singleElement().satisfies(command -> {
            assertThat(command.lines().get(0).accountCode()).isEqualTo("11000");
            assertThat(command.lines().get(0).side()).isEqualTo(monetarySide);
            assertThat(command.lines().get(0).amount()).isEqualByComparingTo("10");
            assertThat(command.lines().get(1).accountCode()).isEqualTo(pnlAccount);
        });
        verify(journals, never()).approveAndPost(any(), any());
        assertThat(directBalances("00000", "99999", new ExecutionContext())).hasSize(1);
    }

    @ParameterizedTest
    @CsvSource({"missingPolicy", "missingMetadata", "unknownCategory", "fixedAssetConflict", "expiredPolicy"})
    void insufficientClassificationFailsPartitionsAndDirectReaders(String defect) {
        configure("11000", "ASSETS", false, MONETARY);
        line(entry("EUR"), "11000", "DEBIT");
        switch (defect) {
            case "missingPolicy" -> properties.setFxValuationPolicies(List.of());
            case "missingMetadata" -> when(metadata.findAccountSubjectAt("11000", DATE)).thenReturn(Optional.empty());
            case "unknownCategory" -> when(metadata.findAccountSubjectAt("11000", DATE)).thenReturn(Optional.of(
                    new AccountSubjectRef("11000", "Unknown", false, false, "DEBIT", null)));
            case "fixedAssetConflict" -> when(metadata.findAccountSubjectAt("11000", DATE)).thenReturn(Optional.of(
                    new AccountSubjectRef("11000", "Fixed", false, true, "DEBIT", "ASSETS")));
            case "expiredPolicy" -> properties.setFxValuationPolicies(List.of(new FxValuationPolicy.Rule(
                    "11000", DATE.minusMonths(1), DATE.minusDays(1), MONETARY)));
        }
        assertThatThrownBy(() -> source.createPartitions(DATE, "USD", 4)).isInstanceOf(IllegalStateException.class);
        assertThatThrownBy(() -> directBalances("11000", "11000", new ExecutionContext()))
                .isInstanceOf(IllegalStateException.class);
    }

    @Test
    void onlyHistoricalAccountsYieldNoPartitionsOrDirectBalances() throws Exception {
        configure("41000", "REVENUE", false, HISTORICAL_COST);
        configure("51000", "EXPENSES", false, HISTORICAL_COST);
        long entry = entry("EUR");
        line(entry, "41000", "CREDIT");
        line(entry, "51000", "DEBIT");
        assertThat(source.createPartitions(DATE, "USD", 4)).isEmpty();
        assertThat(directBalances("00000", "99999", new ExecutionContext())).isEmpty();
    }

    @Test
    void cursorSkipsHistoricalRowsAndRestartsAtPhysicalPositionWithBoundedAccountReuse() throws Exception {
        for (String account : List.of("10000", "12000", "14000")) {
            configure(account, "EXPENSES", false, HISTORICAL_COST);
        }
        for (String account : List.of("11000", "13000")) {
            configure(account, "ASSETS", false, MONETARY);
        }
        long eur = entry("EUR");
        for (String account : List.of("10000", "11000", "12000", "13000", "14000")) {
            line(eur, account, "DEBIT");
        }
        line(entry("GBP"), "11000", "DEBIT");
        var checkpoint = new ExecutionContext();
        var reader = source.createReader(DATE, "USD", "10000", "14000", 1);
        reader.open(checkpoint);
        try {
            assertThat(reader.read().accountCode()).isEqualTo("11000");
            assertThat(reader.read().currencyCode()).isEqualTo("GBP");
            verify(metadata, times(1)).findAccountSubjectAt("11000", DATE);
            reader.update(checkpoint);
        } finally {
            reader.close();
        }
        assertThat(checkpoint.getInt("fxValuationBalanceReader-10000-14000.read.count")).isEqualTo(3);
        assertThat(directBalances("10000", "14000", checkpoint)).singleElement()
                .extracting(FxValuationBalance::accountCode).isEqualTo("13000");
    }

    @Test
    void invalidPostedLineageRemainsFatalForHistoricalAccountOutsideRequestedRange() {
        configure("11000", "ASSETS", false, MONETARY);
        configure("41000", "REVENUE", false, HISTORICAL_COST);
        line(entry("EUR"), "11000", "DEBIT");
        long invalid = entry("USD");
        jdbc.update("""
                UPDATE journal_entries SET entry_type = 'CLOSING_ADJUSTMENT',
                lineage_source_type = 'FX_VALUATION', lineage_source_id = '0|41000|EUR' WHERE id = ?
                """, invalid);
        line(invalid, "41000", "CREDIT");
        assertThatThrownBy(() -> source.createPartitions(DATE, "USD", 4))
                .isInstanceOf(IllegalStateException.class).hasMessageContaining("FX valuation lineage");
        assertThatThrownBy(() -> directBalances("11000", "11000", new ExecutionContext()))
                .isInstanceOf(IllegalStateException.class).hasMessageContaining("FX valuation lineage");
    }

    @Test
    void sourceUsesValuationDateForRuleAndMetadata() throws Exception {
        configure("11000", "ASSETS", false, MONETARY);
        properties.setFxValuationPolicies(List.of(
                new FxValuationPolicy.Rule("11000", DATE.minusMonths(1), DATE.minusDays(1), MONETARY),
                new FxValuationPolicy.Rule("11000", DATE, DATE.plusMonths(1), HISTORICAL_COST)));
        line(entry("EUR"), "11000", "DEBIT");
        assertThat(partitionedBalances()).isEmpty();
        assertThat(directBalances("11000", "11000", new ExecutionContext())).isEmpty();
        verify(metadata, atLeastOnce()).findAccountSubjectAt("11000", DATE);
        verify(metadata, never()).findAccountSubject(any());
    }

    private void configure(String account, String category, boolean fixed, FxValuationPolicy.Treatment treatment) {
        var rules = new ArrayList<>(properties.getFxValuationPolicies());
        rules.add(new FxValuationPolicy.Rule(account, DATE.minusMonths(1), DATE.plusMonths(1), treatment));
        properties.setFxValuationPolicies(rules);
        when(metadata.findAccountSubjectAt(eq(account), any(LocalDate.class))).thenReturn(Optional.of(
                new AccountSubjectRef(account, "Synthetic", false, fixed, "DEBIT", category)));
    }

    private long entry(String currency) {
        long id = ++nextId;
        jdbc.update("INSERT INTO journal_entries (id, status, accounting_date, currency_code) "
                + "VALUES (?, 'POSTED', DATE '2026-05-01', ?)", id, currency);
        return id;
    }

    private void line(long entry, String account, String side) {
        jdbc.update("INSERT INTO journal_details (journal_entry_id, account_code, side, amount, base_amount) "
                + "VALUES (?, ?, ?, 100, 110)", entry, account, side);
    }

    private List<FxValuationBalance> partitionedBalances() throws Exception {
        List<FxValuationBalance> result = new ArrayList<>();
        for (var range : source.createPartitions(DATE, "USD", 4).values()) {
            result.addAll(directBalances(range.getString("startAccountCode"), range.getString("endAccountCode"),
                    new ExecutionContext()));
        }
        return result;
    }

    private List<FxValuationBalance> directBalances(String start, String end, ExecutionContext checkpoint) throws Exception {
        var reader = source.createReader(DATE, "USD", start, end, 2);
        reader.open(checkpoint);
        try {
            List<FxValuationBalance> balances = new ArrayList<>();
            FxValuationBalance balance;
            while ((balance = reader.read()) != null) {
                balances.add(balance);
            }
            return balances;
        } finally {
            reader.close();
        }
    }
}
