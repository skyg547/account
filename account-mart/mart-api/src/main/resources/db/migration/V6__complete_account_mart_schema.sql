-- they cannot be losslessly reinterpreted as the canonical customer/currency/amount flags.
ALTER TABLE ods_coll_mst
    ADD COLUMN customer_code VARCHAR(50),
    ADD COLUMN currency VARCHAR(3),
    ADD COLUMN appraisal_amount NUMERIC(19,4),
    ADD COLUMN pledge_amount NUMERIC(19,4),
    ADD COLUMN is_active BOOLEAN;

-- table_name/error_type/error_msg/created_at are retained as legacy audit evidence.
ALTER TABLE ods_dq_audit
    ADD COLUMN audit_type VARCHAR(30),
    ADD COLUMN audit_message TEXT,
    ADD COLUMN audit_timestamp TIMESTAMP;

