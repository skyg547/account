-- Market data tables. Natural keys used by Optional-returning repositories are unique.
CREATE TABLE market_exchange_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_dt DATE NOT NULL,
    base_currency VARCHAR(3) NOT NULL,
    quote_currency VARCHAR(3) NOT NULL,
    base_rate NUMERIC(19,4) NOT NULL,
    bid_rate NUMERIC(19,4),
    ask_rate NUMERIC(19,4),
    change_amt NUMERIC(10,4),
    change_rate NUMERIC(10,4),
    source VARCHAR(50),
    created_at TIMESTAMP,
    CONSTRAINT uq_market_exchange_rate
        UNIQUE (base_currency, quote_currency, base_dt)
);

CREATE TABLE market_rate (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_dt DATE NOT NULL,
    rate_name VARCHAR(50) NOT NULL,
    rate_type VARCHAR(20),
    currency VARCHAR(3),
    tenor_months INTEGER,
    tenor_label VARCHAR(10),
    rate NUMERIC(10,6) NOT NULL,
    change_bp NUMERIC(10,2),
    source VARCHAR(50),
    is_active BOOLEAN,
    created_at TIMESTAMP,
    CONSTRAINT uq_market_rate_repository_key
        UNIQUE NULLS NOT DISTINCT (base_dt, rate_name, tenor_months)
);

CREATE TABLE market_yield_curve (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_dt DATE NOT NULL,
    currency VARCHAR(3),
    curve_name VARCHAR(255),
    description VARCHAR(255),
    is_active BOOLEAN,
    created_at TIMESTAMP,
    CONSTRAINT uq_market_yield_curve_repository_key
        UNIQUE NULLS NOT DISTINCT (curve_name, base_dt)
);

CREATE TABLE market_yield_curve_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    curve_id BIGINT,
    tenor_label VARCHAR(10),
    tenor_months INTEGER,
    rate NUMERIC(10,6),
    discount_factor NUMERIC(19,12),
    CONSTRAINT fk_market_yield_curve_point_curve
        FOREIGN KEY (curve_id) REFERENCES market_yield_curve(id),
    CONSTRAINT uq_market_yield_curve_point_repository_key
        UNIQUE NULLS NOT DISTINCT (curve_id, tenor_months)
);

-- Relational integrity for canonical ODS identifiers. Existing rows are retained; the
-- partitioned balance history FK is validated because PostgreSQL does not support a
-- NOT VALID foreign key on a partitioned parent.
DO $$
DECLARE
    orphan_count BIGINT;
BEGIN
    SELECT COUNT(*)
      INTO orphan_count
      FROM ods_balance_hist history
      LEFT JOIN ods_acc_ledger ledger ON ledger.acc_no = history.account_no
     WHERE ledger.acc_no IS NULL;

    IF orphan_count > 0 THEN
        RAISE EXCEPTION
            'Cannot add ods_balance_hist account FK: % orphan history rows exist',
            orphan_count
            USING HINT =
                'Load the matching ods_acc_ledger accounts or remove invalid history through an approved data repair, then rerun Flyway.';
    END IF;
END
$$;

