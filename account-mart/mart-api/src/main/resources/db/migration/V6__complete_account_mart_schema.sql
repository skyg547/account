ALTER TABLE ods_coll_mst RENAME COLUMN coll_type TO collateral_type;
ALTER TABLE ods_coll_mst RENAME COLUMN appraisal_dt TO appraisal_date;

ALTER TABLE ods_balance_hist RENAME COLUMN acc_no TO account_no;
ALTER TABLE ods_balance_hist RENAME COLUMN cur_bal TO balance;

ALTER TABLE ods_dq_audit RENAME COLUMN base_dt TO base_date;
ALTER TABLE ods_dq_audit RENAME COLUMN acc_no TO account_no;

