    ON gl_balances (account_code, currency_code, balance_date);
CREATE INDEX IF NOT EXISTS idx_gl_balance_period
    ON gl_balances (period, account_code);
CREATE INDEX IF NOT EXISTS idx_journal_detail_journal_entry_id
    ON journal_details (journal_entry_id);
CREATE INDEX IF NOT EXISTS idx_journal_detail_account_code
    ON journal_details (account_code);
CREATE INDEX IF NOT EXISTS idx_journal_detail_dept_code
    ON journal_details (dept_code);
CREATE INDEX IF NOT EXISTS idx_journal_detail_business_partner_code
    ON journal_details (business_partner_code);
CREATE INDEX IF NOT EXISTS idx_journal_detail_side
    ON journal_details (side);
CREATE INDEX IF NOT EXISTS idx_journal_entry_slip_no
    ON journal_entries (slip_no);
CREATE INDEX IF NOT EXISTS idx_journal_entry_posting_lookup
    ON journal_entries (status, accounting_date);
CREATE INDEX IF NOT EXISTS idx_journal_entry_lineage
    ON journal_entries (lineage_source_type, lineage_source_id);
CREATE INDEX IF NOT EXISTS idx_journal_rule_code_valid
    ON journal_rules (rule_code, valid_from, valid_to);
CREATE INDEX IF NOT EXISTS idx_sl_balance_lookup
    ON sl_balances (account_code, bp_code, dept_code, balance_date);
CREATE INDEX IF NOT EXISTS idx_sl_balance_period
    ON sl_balances (period, account_code);
