export interface FinancialStatementDto {
  accountCode: string;
  accountName: string;
  amountCurrent: number;
  amountPrevious: number;
  variance: number;
  statementType?: 'BS' | 'IS';
  category?: string;
  level?: number;
  parentId?: string | null;
  children?: FinancialStatementDto[];
}

export interface ReportExportHistoryDto {
  id: string;
  reportName: string;
  reportType: 'BS' | 'IS' | 'CASH_FLOW' | 'REGULATORY' | 'DISCLOSURE';
  format: 'PDF' | 'EXCEL';
  period: string;
  createdAt: string;
  createdBy: string;
  fileSize: string;
  status: 'COMPLETED' | 'PROCESSING' | 'FAILED';
  downloadUrl?: string;
}

export interface DisclosureNoteDto {
  id: string;
  noteNumber: number;
  title: string;
  category: string;
  relatedAccountCodes: string[];
  currentAmount: number;
  previousAmount: number;
  details: {
    item: string;
    description: string;
    currentValue: number;
    previousValue: number;
  }[];
}

export interface RegulatorySubmissionDto {
  id: string;
  formType: 'FSS_KIFRS' | 'TAX_VAT' | 'TAX_CIT' | 'BANK_REGULATORY';
  title: string;
  reportingPeriod: string;
  dueDate: string;
  submissionDate?: string;
  status: 'DRAFT' | 'PENDING_APPROVAL' | 'SUBMITTED' | 'REJECTED';
  submittedBy?: string;
  reviewer?: string;
  remarks?: string;
}

