-- Absorb dates outside the initially published 2026-04 result partition. This keeps a fresh
-- install and later accounting periods writable without rewriting the immutable V1 baseline.
CREATE TABLE allowance_ecl_results_default
    PARTITION OF allowance_ecl_results DEFAULT;

