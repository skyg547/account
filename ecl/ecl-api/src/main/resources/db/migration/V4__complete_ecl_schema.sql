-- Complete the ECL persistence contract without modifying the published V1-V3 migrations.

-- The runtime entity already accepts 20 characters. Widening is non-lossy for existing rows.
ALTER TABLE cr_accounts
    ALTER COLUMN original_rating TYPE VARCHAR(20);

-- CrCollateral requires an owning customer. Refuse to hide legacy orphan rows so that an
-- operator can repair them explicitly before retrying this forward-only migration.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM cr_collaterals WHERE customer_id IS NULL) THEN
        RAISE EXCEPTION
            'Cannot enforce cr_collaterals.customer_id NOT NULL: orphan collateral rows exist'
            USING HINT = 'Assign every collateral to a valid cr_customers.id, then rerun Flyway.';
    END IF;
END
$$;

ALTER TABLE cr_collaterals
    ALTER COLUMN customer_id SET NOT NULL;

-- CrAccountCollateral inherits the shared auditing mapping, while the published V1 table
-- omitted the actor columns.
ALTER TABLE cr_account_collaterals
    ADD COLUMN IF NOT EXISTS created_by VARCHAR(255),
    ADD COLUMN IF NOT EXISTS updated_by VARCHAR(255);

-- Lifetime-PD transition matrix used by JpaTransitionMatrixRepository.
CREATE TABLE transition_matrix (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    base_date DATE NOT NULL,
    from_rating VARCHAR(10) NOT NULL,
    to_rating VARCHAR(10) NOT NULL,
    probability NUMERIC(10,6) NOT NULL,
    time_horizon INTEGER DEFAULT 1,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    created_by VARCHAR(255),
    updated_by VARCHAR(255),
    CONSTRAINT uq_transition_matrix_rating_path
        UNIQUE (base_date, from_rating, to_rating)
);

