-- Immutable source receipts are committed with lease balances under the existing contract row lock.
CREATE TABLE lease_remeasurement_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_no VARCHAR(100) NOT NULL,
    operation_id VARCHAR(80) NOT NULL,
    fingerprint_version INTEGER NOT NULL CHECK (fingerprint_version = 1),
    request_fingerprint VARCHAR(64) NOT NULL,
    contract_id BIGINT NOT NULL REFERENCES lease_contracts(id),
    remeasure_date DATE NOT NULL,
    adjustment_amount NUMERIC(19,2) NOT NULL,
    old_liability_amount NUMERIC(19,2) NOT NULL,
    new_liability_amount NUMERIC(19,2) NOT NULL,
    department_code VARCHAR(20),
    actor VARCHAR(255) NOT NULL,
    CONSTRAINT uk_lease_remeasurement_operation UNIQUE (contract_no, operation_id)
);
