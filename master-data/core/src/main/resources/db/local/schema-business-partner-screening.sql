-- Local H2 equivalent of V11; local Flyway stops at V8 before PostgreSQL-only V9.
CREATE TABLE IF NOT EXISTS business_partner_screenings (
    business_partner_code VARCHAR(20) PRIMARY KEY,
    jurisdiction VARCHAR(2) NOT NULL,
    identifier_type VARCHAR(64) NOT NULL,
    identifier VARCHAR(128) NOT NULL,
    evidence_reference VARCHAR(512) NOT NULL,
    evidence_expires_on DATE,
    status VARCHAR(30) NOT NULL,
    risk_rating VARCHAR(20) NOT NULL,
    submitted_by VARCHAR(128) NOT NULL,
    submitted_at TIMESTAMP(6) NOT NULL,
    reviewed_by VARCHAR(128),
    decision_reason VARCHAR(1000),
    decided_at TIMESTAMP(6),
    CONSTRAINT ck_bp_screenings_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVIEW_REQUIRED')),
    CONSTRAINT ck_bp_screenings_risk CHECK (risk_rating IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_bp_screenings_decision CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND decision_reason IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND decision_reason IS NOT NULL AND decided_at IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS business_partner_screening_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_partner_code VARCHAR(20) NOT NULL,
    jurisdiction VARCHAR(2) NOT NULL,
    identifier_type VARCHAR(64) NOT NULL,
    identifier VARCHAR(128) NOT NULL,
    evidence_reference VARCHAR(512) NOT NULL,
    evidence_expires_on DATE,
    status VARCHAR(30) NOT NULL,
    risk_rating VARCHAR(20) NOT NULL,
    submitted_by VARCHAR(128) NOT NULL,
    submitted_at TIMESTAMP(6) NOT NULL,
    reviewed_by VARCHAR(128),
    decision_reason VARCHAR(1000),
    decided_at TIMESTAMP(6),
    CONSTRAINT ck_bp_screening_audit_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVIEW_REQUIRED')),
    CONSTRAINT ck_bp_screening_audit_risk CHECK (risk_rating IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_bp_screening_audit_decision CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND decision_reason IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND decision_reason IS NOT NULL AND decided_at IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS idx_bp_screening_audit_code_id
    ON business_partner_screening_audit (business_partner_code, id);
