-- Screening is keyed by stable business code, not the versioned business_partners.id.
-- The application holds master_data_business_key_locks(BUSINESS_PARTNER, code) before writes.
CREATE TABLE business_partner_screenings (
    business_partner_code VARCHAR(20) PRIMARY KEY,
    jurisdiction VARCHAR(2) NOT NULL,
    identifier_type VARCHAR(64) NOT NULL,
    identifier VARCHAR(128) NOT NULL,
    evidence_reference VARCHAR(512) NOT NULL,
    evidence_expires_on DATE,
    status VARCHAR(30) NOT NULL,
    risk_rating VARCHAR(20) NOT NULL,
    submitted_by VARCHAR(128) NOT NULL,
    submitted_at TIMESTAMP(6) NOT NULL,
    reviewed_by VARCHAR(128),
    decision_reason VARCHAR(1000),
    decided_at TIMESTAMP(6),
    CONSTRAINT ck_bp_screenings_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVIEW_REQUIRED')),
    CONSTRAINT ck_bp_screenings_risk CHECK (risk_rating IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_bp_screenings_decision CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND decision_reason IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND decision_reason IS NOT NULL AND decided_at IS NOT NULL)
    )
);

-- Each submission and each review is a separate complete snapshot. No FK to a current row:
-- resubmission, SCD2 replacement, and later lifecycle changes cannot delete audit history.
CREATE TABLE business_partner_screening_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_partner_code VARCHAR(20) NOT NULL,
    jurisdiction VARCHAR(2) NOT NULL,
    identifier_type VARCHAR(64) NOT NULL,
    identifier VARCHAR(128) NOT NULL,
    evidence_reference VARCHAR(512) NOT NULL,
    evidence_expires_on DATE,
    status VARCHAR(30) NOT NULL,
    risk_rating VARCHAR(20) NOT NULL,
    submitted_by VARCHAR(128) NOT NULL,
    submitted_at TIMESTAMP(6) NOT NULL,
    reviewed_by VARCHAR(128),
    decision_reason VARCHAR(1000),
    decided_at TIMESTAMP(6),
    CONSTRAINT ck_bp_screening_audit_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'REVIEW_REQUIRED')),
    CONSTRAINT ck_bp_screening_audit_risk CHECK (risk_rating IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_bp_screening_audit_decision CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND decision_reason IS NULL AND decided_at IS NULL)
        OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND decision_reason IS NOT NULL AND decided_at IS NOT NULL)
    )
);

CREATE INDEX idx_bp_screening_audit_code_id
    ON business_partner_screening_audit (business_partner_code, id);

-- As-of eligibility selects one event by this exact expression and order.
-- Keep the code/id index for chronological audit retrieval without a computed sort.
CREATE INDEX idx_bp_screening_audit_code_event_id
    ON business_partner_screening_audit
    (business_partner_code, (COALESCE(decided_at, submitted_at)) DESC, id DESC);

-- Database protection complements the insert-only JPA mapping. The trigger reports no row values.
CREATE FUNCTION reject_business_partner_screening_audit_change()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Screening audit rows are immutable';
END;
$$;

CREATE TRIGGER trg_bp_screening_audit_immutable
    BEFORE UPDATE OR DELETE ON business_partner_screening_audit
    FOR EACH ROW EXECUTE FUNCTION reject_business_partner_screening_audit_change();
