-- Auth owns these governance tables. TEXT works on PostgreSQL and H2 without CLOB/OID semantics.
CREATE TABLE system_role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code VARCHAR(50) NOT NULL UNIQUE,
    role_name VARCHAR(100) NOT NULL,
    description VARCHAR(500),
    create_date TIMESTAMP NOT NULL,
    update_date TIMESTAMP NOT NULL,
    audit_user VARCHAR(80) NOT NULL
);
CREATE TABLE audit_authorizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES system_role(id),
    function_code VARCHAR(100) NOT NULL,
    access_type VARCHAR(20) NOT NULL,
    data_scope VARCHAR(200),
    create_date TIMESTAMP NOT NULL,
    update_date TIMESTAMP NOT NULL,
    audit_user VARCHAR(80) NOT NULL,
    UNIQUE (role_id, function_code, access_type)
);
CREATE TABLE master_approval (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    master_type VARCHAR(50) NOT NULL,
    master_key VARCHAR(100) NOT NULL,
    request_type VARCHAR(20) NOT NULL,
    payload TEXT,
    request_user VARCHAR(80) NOT NULL,
    request_date TIMESTAMP NOT NULL,
    approver_user VARCHAR(80),
    approval_date TIMESTAMP,
    status VARCHAR(20) NOT NULL,
    effective_date DATE,
    requested_version INTEGER,
    remarks VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    audit_user VARCHAR(80) NOT NULL
);
CREATE INDEX idx_master_approval_status ON master_approval(status, id);
CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(50) NOT NULL,
    event_date_time TIMESTAMP NOT NULL,
    user_id VARCHAR(80) NOT NULL,
    target_entity VARCHAR(100) NOT NULL,
    target_id VARCHAR(100) NOT NULL,
    before_data TEXT,
    after_data TEXT,
    status VARCHAR(20),
    remarks VARCHAR(1000),
    ip_address VARCHAR(50),
    create_date TIMESTAMP NOT NULL,
    update_date TIMESTAMP NOT NULL,
    audit_user VARCHAR(80) NOT NULL
);
CREATE INDEX idx_audit_log_time ON audit_log(event_date_time);
CREATE INDEX idx_audit_log_user ON audit_log(user_id, event_date_time);
