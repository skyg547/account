
-- 31. RECONCILIATION_RESULTS (대사 결과)
CREATE TABLE RECONCILIATION_RESULTS
(
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- 대사 결과 ID (PK)
    RECONCILIATION_DATE DATE NOT NULL,                              -- 대사 일자
    RECONCILIATION_TYPE VARCHAR2(50) NOT NULL,                      -- 대사 유형 (SOURCE_STANDARD, ACCOUNT_TOTALS, BANK_ACCOUNT)
    CLOSING_PERIOD_ID NUMBER,                                       -- 마감 기간 ID (FK, optional)
    STATUS VARCHAR2(50) NOT NULL,                                   -- 상태 (SUCCESS, VARIANCE_FOUND, ERROR)
    TOTAL_COUNT_SOURCE NUMBER(19) NOT NULL,                         -- 원천 데이터 건수
    TOTAL_AMOUNT_SOURCE NUMBER(19, 2) NOT NULL,                     -- 원천 데이터 금액
    TOTAL_COUNT_TARGET NUMBER(19) NOT NULL,                         -- 대상 데이터 건수
    TOTAL_AMOUNT_TARGET NUMBER(19, 2) NOT NULL,                     -- 대상 데이터 금액
    VARIANCE_COUNT NUMBER(19) NOT NULL,                             -- 차이 건수
    VARIANCE_AMOUNT NUMBER(19, 2) NOT NULL,                         -- 차이 금액
    RUN_BY VARCHAR2(50),                                            -- 실행자
    RUN_AT TIMESTAMP,                                               -- 실행 일시
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,            -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,            -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL               -- 감사 사용자
);

COMMENT ON TABLE RECONCILIATION_RESULTS IS '대사 결과';
COMMENT ON COLUMN RECONCILIATION_RESULTS.ID IS '대사 결과 ID';
COMMENT ON COLUMN RECONCILIATION_RESULTS.RECONCILIATION_DATE IS '대사 일자';
COMMENT ON COLUMN RECONCILIATION_RESULTS.RECONCILIATION_TYPE IS '대사 유형';
COMMENT ON COLUMN RECONCILIATION_RESULTS.CLOSING_PERIOD_ID IS '마감 기간 ID';
COMMENT ON COLUMN RECONCILIATION_RESULTS.STATUS IS '상태';
COMMENT ON COLUMN RECONCILIATION_RESULTS.TOTAL_COUNT_SOURCE IS '원천 데이터 건수';
COMMENT ON COLUMN RECONCILIATION_RESULTS.TOTAL_AMOUNT_SOURCE IS '원천 데이터 금액';
COMMENT ON COLUMN RECONCILIATION_RESULTS.TOTAL_COUNT_TARGET IS '대상 데이터 건수';
COMMENT ON COLUMN RECONCILIATION_RESULTS.TOTAL_AMOUNT_TARGET IS '대상 데이터 금액';
COMMENT ON COLUMN RECONCILIATION_RESULTS.VARIANCE_COUNT IS '차이 건수';
COMMENT ON COLUMN RECONCILIATION_RESULTS.VARIANCE_AMOUNT IS '차이 금액';
COMMENT ON COLUMN RECONCILIATION_RESULTS.RUN_BY IS '실행자';
COMMENT ON COLUMN RECONCILIATION_RESULTS.RUN_AT IS '실행 일시';
COMMENT ON COLUMN RECONCILIATION_RESULTS.CREATE_DATE IS '생성일';
COMMENT ON COLUMN RECONCILIATION_RESULTS.UPDATE_DATE IS '수정일';
COMMENT ON COLUMN RECONCILIATION_RESULTS.AUDIT_USER IS '감사 사용자';

CREATE INDEX IDX_RR_DATE_TYPE ON RECONCILIATION_RESULTS (RECONCILIATION_DATE, RECONCILIATION_TYPE);


-- 32. RECONCILIATION_VARIANCES (대사 차이)
CREATE TABLE RECONCILIATION_VARIANCES
(
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- 대사 차이 ID (PK)
    RECONCILIATION_RESULT_ID NUMBER NOT NULL,                       -- 대사 결과 ID (FK)
    VARIANCE_CODE VARCHAR2(50) NOT NULL,                            -- 차이 코드
    DESCRIPTION VARCHAR2(500) NOT NULL,                             -- 차이 설명
    AMOUNT NUMBER(19, 2) NOT NULL,                                  -- 차이 금액
    DR_CR_TYPE VARCHAR2(10),                                        -- 차변/대변 구분
    SOURCE_REFERENCE VARCHAR2(255),                                 -- 원천 참조값
    TARGET_REFERENCE VARCHAR2(255),                                 -- 대상 참조값
    ADJUSTMENT_JOURNAL_ENTRY_ID NUMBER,                             -- 조정 전표 ID (FK, optional)
    STATUS VARCHAR2(50) NOT NULL,                                   -- 상태 (OPEN, ADJUSTED, IGNORED)
    RESOLVED_BY VARCHAR2(50),                                       -- 해결자
    RESOLVED_AT TIMESTAMP,                                          -- 해결 일시
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,            -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,            -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL,              -- 감사 사용자

    CONSTRAINT FK_RV_RECON_RESULT_ID FOREIGN KEY (RECONCILIATION_RESULT_ID) REFERENCES RECONCILIATION_RESULTS (ID),
    CONSTRAINT FK_RV_ADJ_JOURNAL_ID FOREIGN KEY (ADJUSTMENT_JOURNAL_ENTRY_ID) REFERENCES JOURNAL_ENTRY (ID)
);

COMMENT ON TABLE RECONCILIATION_VARIANCES IS '대사 차이';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.ID IS '대사 차이 ID';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.RECONCILIATION_RESULT_ID IS '대사 결과 ID';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.VARIANCE_CODE IS '차이 코드';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.DESCRIPTION IS '차이 설명';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.AMOUNT IS '차이 금액';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.DR_CR_TYPE IS '차변/대변 구분';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.SOURCE_REFERENCE IS '원천 참조값';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.TARGET_REFERENCE IS '대상 참조값';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.ADJUSTMENT_JOURNAL_ENTRY_ID IS '조정 전표 ID';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.STATUS IS '상태';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.RESOLVED_BY IS '해결자';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.RESOLVED_AT IS '해결 일시';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.CREATE_DATE IS '생성일';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.UPDATE_DATE IS '수정일';
COMMENT ON COLUMN RECONCILIATION_VARIANCES.AUDIT_USER IS '감사 사용자';

CREATE INDEX IDX_RV_RECON_RESULT_ID ON RECONCILIATION_VARIANCES (RECONCILIATION_RESULT_ID);


-- 33. BANK_STATEMENTS (은행 거래 내역)
CREATE TABLE BANK_STATEMENTS
(
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- ID (PK)
    BANK_CODE VARCHAR2(20) NOT NULL,                                -- 은행 코드
    ACCOUNT_NO VARCHAR2(50) NOT NULL,                               -- 계좌 번호
    TRANSACTION_DATE DATE NOT NULL,                                  -- 거래 일자
    VALUE_DATE DATE,                                                 -- 기산일
    DESCRIPTION VARCHAR2(500),                                       -- 거래 내용 (적요)
    WITHDRAWAL_AMOUNT NUMBER(19, 2) DEFAULT 0.00 NOT NULL,           -- 출금 금액
    DEPOSIT_AMOUNT NUMBER(19, 2) DEFAULT 0.00 NOT NULL,              -- 입금 금액
    BALANCE NUMBER(19, 2),                                           -- 잔액
    BRANCH_NAME VARCHAR2(100),                                       -- 지점명
    TRANSACTION_TIME TIMESTAMP,                                      -- 거래 시각
    RECONCILIATION_STATUS VARCHAR2(20) DEFAULT 'UNMATCHED' NOT NULL, -- 대사 상태 (UNMATCHED, MATCHED, EXCLUDED)
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,             -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,             -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL                -- 감사 사용자
);

COMMENT ON TABLE BANK_STATEMENTS IS '은행 거래 내역 (대사용)';
COMMENT ON COLUMN BANK_STATEMENTS.BANK_CODE IS '은행 코드';
COMMENT ON COLUMN BANK_STATEMENTS.ACCOUNT_NO IS '계좌 번호';
COMMENT ON COLUMN BANK_STATEMENTS.TRANSACTION_DATE IS '거래 일자';
COMMENT ON COLUMN BANK_STATEMENTS.DESCRIPTION IS '거래 내용';
COMMENT ON COLUMN BANK_STATEMENTS.WITHDRAWAL_AMOUNT IS '출금 금액';
COMMENT ON COLUMN BANK_STATEMENTS.DEPOSIT_AMOUNT IS '입금 금액';
COMMENT ON COLUMN BANK_STATEMENTS.RECONCILIATION_STATUS IS '대사 상태';

CREATE INDEX IDX_BS_DATE_ACCOUNT ON BANK_STATEMENTS (TRANSACTION_DATE, ACCOUNT_NO);
CREATE INDEX IDX_BS_STATUS ON BANK_STATEMENTS (RECONCILIATION_STATUS);
