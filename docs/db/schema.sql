    START_DATE DATE NOT NULL,                                      -- 시작일
    END_DATE DATE NOT NULL,                                        -- 종료일
    MONTHLY_PAYMENT NUMBER(19, 2) NOT NULL,                        -- 월 리스료
    PAYMENT_DAY NUMBER(2) NOT NULL,                                -- 매월 지급일 (예: 25일)
    DEPT_CODE VARCHAR2(20),                                        -- 관리 부서코드 (FK)
