COMMENT ON TABLE CUSTOMER IS '거래처';
COMMENT ON COLUMN CUSTOMER.CUSTOMER_CODE IS '거래처코드';
COMMENT ON COLUMN CUSTOMER.CUSTOMER_NAME IS '거래처명';
COMMENT ON COLUMN CUSTOMER.BUSINESS_REG_NO IS '사업자등록번호';
