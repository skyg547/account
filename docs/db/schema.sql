-- 4. FIXED_ASSETS (고정자산)
CREATE TABLE FIXED_ASSETS
(
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- 고정자산 ID (PK)
    ASSET_CODE VARCHAR2(20) UNIQUE NOT NULL,                       -- 자산코드 (고유)
    ASSET_NAME VARCHAR2(100) NOT NULL,                             -- 자산명
    ACCOUNT_CODE VARCHAR2(20) NOT NULL,                           -- 자산 계정코드 (FK)
    ACCUMULATED_ACCOUNT_CODE VARCHAR2(20),                        -- 감가상각누계액 계정코드 (FK)
    EXPENSE_ACCOUNT_CODE VARCHAR2(20),                            -- 감가상각비 계정코드 (FK)
    ACQUISITION_DATE DATE NOT NULL,                               -- 취득일
    ACQUISITION_COST NUMBER(19, 2) NOT NULL,                      -- 취득원가
    USEFUL_LIFE NUMBER(3) NOT NULL,                               -- 내용연수 (년)
    DEPRECIATION_METHOD VARCHAR2(20),                             -- 감가상각방법 (STRAIGHT_LINE, DECLINING)
    RESIDUAL_VALUE NUMBER(19, 2) DEFAULT 0.00,                    -- 잔존가치
    ACCUMULATED_DEPRECIATION NUMBER(19, 2) DEFAULT 0.00,          -- 현재까지의 감가상각누계액
    DEPT_CODE VARCHAR2(20),                                       -- 관리 부서코드 (FK)
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,               -- 상태 (ACTIVE, DISPOSED, FULLY_DEPRECIATED)
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,          -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,          -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL,            -- 감사 사용자

    CONSTRAINT FK_FA_ACCOUNT_CODE FOREIGN KEY (ACCOUNT_CODE) REFERENCES ACCOUNT_SUBJECT (ACCOUNT_CODE),
    CONSTRAINT FK_FA_ACCUMULATED_CODE FOREIGN KEY (ACCUMULATED_ACCOUNT_CODE) REFERENCES ACCOUNT_SUBJECT (ACCOUNT_CODE),
    CONSTRAINT FK_FA_EXPENSE_CODE FOREIGN KEY (EXPENSE_ACCOUNT_CODE) REFERENCES ACCOUNT_SUBJECT (ACCOUNT_CODE),
    CONSTRAINT FK_FA_DEPT_CODE FOREIGN KEY (DEPT_CODE) REFERENCES DEPARTMENT (DEPT_CODE)
);

COMMENT ON TABLE FIXED_ASSETS IS '고정자산';
COMMENT ON COLUMN FIXED_ASSETS.ID IS '고정자산 ID';
COMMENT ON COLUMN FIXED_ASSETS.ASSET_CODE IS '자산코드';
COMMENT ON COLUMN FIXED_ASSETS.ASSET_NAME IS '자산명';
COMMENT ON COLUMN FIXED_ASSETS.ACCOUNT_CODE IS '자산 계정코드';
COMMENT ON COLUMN FIXED_ASSETS.ACCUMULATED_ACCOUNT_CODE IS '감가상각누계액 계정코드';
COMMENT ON COLUMN FIXED_ASSETS.EXPENSE_ACCOUNT_CODE IS '감가상각비 계정코드';
COMMENT ON COLUMN FIXED_ASSETS.ACQUISITION_DATE IS '취득일';
COMMENT ON COLUMN FIXED_ASSETS.ACQUISITION_COST IS '취득원가';
COMMENT ON COLUMN FIXED_ASSETS.USEFUL_LIFE IS '내용연수 (년)';
COMMENT ON COLUMN FIXED_ASSETS.DEPRECIATION_METHOD IS '감가상각방법';
COMMENT ON COLUMN FIXED_ASSETS.RESIDUAL_VALUE IS '잔존가치';
COMMENT ON COLUMN FIXED_ASSETS.ACCUMULATED_DEPRECIATION IS '현재까지의 감가상각누계액';
COMMENT ON COLUMN FIXED_ASSETS.DEPT_CODE IS '관리 부서코드';
COMMENT ON COLUMN FIXED_ASSETS.STATUS IS '상태';
COMMENT ON COLUMN FIXED_ASSETS.CREATE_DATE IS '생성일';
COMMENT ON COLUMN FIXED_ASSETS.UPDATE_DATE IS '수정일';
COMMENT ON COLUMN FIXED_ASSETS.AUDIT_USER IS '감사 사용자';

CREATE INDEX IDX_FA_ASSET_CODE ON FIXED_ASSETS (ASSET_CODE);
CREATE INDEX IDX_FA_ACCOUNT_CODE ON FIXED_ASSETS (ACCOUNT_CODE);
CREATE INDEX IDX_FA_DEPT_CODE ON FIXED_ASSETS (DEPT_CODE);


-- 5. LEASE_CONTRACTS (리스 계약)
