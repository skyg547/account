    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,           -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,           -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL,             -- 감사 사용자

    CONSTRAINT FK_LC_LESSOR_CUSTOMER_CODE FOREIGN KEY (LESSOR_CUSTOMER_CODE) REFERENCES CUSTOMER (CUSTOMER_CODE),
    CONSTRAINT FK_LC_DEPT_CODE FOREIGN KEY (DEPT_CODE) REFERENCES DEPARTMENT (DEPT_CODE),
    CONSTRAINT FK_LC_EXPENSE_ACCOUNT_CODE FOREIGN KEY (EXPENSE_ACCOUNT_CODE) REFERENCES ACCOUNT_SUBJECT (ACCOUNT_CODE)
