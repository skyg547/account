-- 9. BUDGET (예산)
CREATE TABLE BUDGET
(
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- 예산 ID (PK)
    BUDGET_CODE VARCHAR2(20) UNIQUE NOT NULL,                      -- 예산코드 (고유)
    BUDGET_NAME VARCHAR2(100) NOT NULL,                            -- 예산명
    FISCAL_YEAR VARCHAR2(4) NOT NULL,                              -- 회계연도
    DEPT_CODE VARCHAR2(20) NOT NULL,                               -- 부서코드 (FK)
    ACCOUNT_CODE VARCHAR2(20) NOT NULL,                           -- 계정코드 (FK)
    ALLOCATED_AMOUNT NUMBER(19, 2) NOT NULL,                       -- 할당금액
    EXECUTED_AMOUNT NUMBER(19, 2) DEFAULT 0.00 NOT NULL,           -- 집행금액
    REMAINING_AMOUNT NUMBER(19, 2) NOT NULL,                       -- 잔여금액
    STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,                -- 상태 (ACTIVE, CLOSED)
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,           -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,           -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL,             -- 감사 사용자

    CONSTRAINT FK_BGT_DEPT_CODE FOREIGN KEY (DEPT_CODE) REFERENCES DEPARTMENT (DEPT_CODE),
    CONSTRAINT FK_BGT_ACCOUNT_CODE FOREIGN KEY (ACCOUNT_CODE) REFERENCES ACCOUNT_SUBJECT (ACCOUNT_CODE),
    CONSTRAINT UDX_BGT_FISCAL_DEPT_ACC UNIQUE (FISCAL_YEAR, DEPT_CODE, ACCOUNT_CODE) -- 회계연도, 부서, 계정과목별 예산 고유성
);

