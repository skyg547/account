COMMENT ON COLUMN LEASE_CONTRACTS.END_DATE IS '종료일';
COMMENT ON COLUMN LEASE_CONTRACTS.MONTHLY_PAYMENT IS '월 리스료';
COMMENT ON COLUMN LEASE_CONTRACTS.PAYMENT_DAY IS '매월 지급일';
COMMENT ON COLUMN LEASE_CONTRACTS.DEPT_CODE IS '관리 부서코드';
COMMENT ON COLUMN LEASE_CONTRACTS.EXPENSE_ACCOUNT_CODE IS '리스료 비용 계정코드';
