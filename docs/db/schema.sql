-- 3. CUSTOMER (거래처)
CREATE TABLE CUSTOMER
(
    CUSTOMER_CODE VARCHAR2(20) NOT NULL PRIMARY KEY, -- 거래처코드 (PK)
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,            -- 거래처명
