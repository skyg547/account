-- 6. EXCHANGE_RATE (환율)
CREATE TABLE EXCHANGE_RATE
(
    BASE_CURRENCY_CODE VARCHAR2(3) NOT NULL,                     -- 기준 통화 코드 (PK, FK)
    TARGET_CURRENCY_CODE VARCHAR2(3) NOT NULL,                   -- 대상 통화 코드 (PK, FK)
    APPLY_DATE DATE NOT NULL,                                    -- 적용 일자 (PK)
    RATE NUMBER(19, 8) NOT NULL,                                 -- 환율 (소수점 8자리)
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,         -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,         -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL,           -- 감사 사용자

    CONSTRAINT PK_EXCHANGE_RATE PRIMARY KEY (BASE_CURRENCY_CODE, TARGET_CURRENCY_CODE, APPLY_DATE),
    CONSTRAINT FK_ER_BASE_CURRENCY_CODE FOREIGN KEY (BASE_CURRENCY_CODE) REFERENCES CURRENCY (CURRENCY_CODE),
    CONSTRAINT FK_ER_TARGET_CURRENCY_CODE FOREIGN KEY (TARGET_CURRENCY_CODE) REFERENCES CURRENCY (CURRENCY_CODE)
);

COMMENT ON TABLE EXCHANGE_RATE IS '환율';
COMMENT ON COLUMN EXCHANGE_RATE.BASE_CURRENCY_CODE IS '기준 통화 코드';
COMMENT ON COLUMN EXCHANGE_RATE.TARGET_CURRENCY_CODE IS '대상 통화 코드';
COMMENT ON COLUMN EXCHANGE_RATE.APPLY_DATE IS '적용 일자';
COMMENT ON COLUMN EXCHANGE_RATE.RATE IS '환율';
COMMENT ON COLUMN EXCHANGE_RATE.CREATE_DATE IS '생성일';
COMMENT ON COLUMN EXCHANGE_RATE.UPDATE_DATE IS '수정일';
COMMENT ON COLUMN EXCHANGE_RATE.AUDIT_USER IS '감사 사용자';

CREATE UNIQUE INDEX UDX_EXCH_RATE_UNIQUE ON EXCHANGE_RATE (BASE_CURRENCY_CODE, TARGET_CURRENCY_CODE, APPLY_DATE);

