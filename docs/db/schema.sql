-- K-Bank 차세대 재무 시스템 스키마 설계 (Oracle/PostgreSQL 호환)

-- 1. ACCOUNT_SUBJECT (계정과목)
CREATE TABLE ACCOUNT_SUBJECT
(
    ACCOUNT_CODE VARCHAR2(20) NOT NULL PRIMARY KEY, -- 계정코드 (PK)
    ACCOUNT_NAME VARCHAR2(100) NOT NULL,            -- 계정명
    ACCOUNT_TYPE VARCHAR2(20) NOT NULL,            -- 계정유형 (자산, 부채, 자본, 수익, 비용)
    PARENT_ACCOUNT_CODE VARCHAR2(20),             -- 상위 계정코드 (FK)
    VALID_FROM_DATE DATE DEFAULT SYSDATE NOT NULL, -- 유효 시작일 (SCD2)
    VALID_TO_DATE DATE,                               -- 유효 종료일 (SCD2)
    IS_USED CHAR(1) DEFAULT 'Y' NOT NULL,        -- 사용여부 (Y/N)
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL, -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL   -- 감사 사용자
);

COMMENT ON TABLE ACCOUNT_SUBJECT IS '계정과목';
COMMENT ON COLUMN ACCOUNT_SUBJECT.ACCOUNT_CODE IS '계정코드';
COMMENT ON COLUMN ACCOUNT_SUBJECT.ACCOUNT_NAME IS '계정명';
COMMENT ON COLUMN ACCOUNT_SUBJECT.ACCOUNT_TYPE IS '계정유형';
COMMENT ON COLUMN ACCOUNT_SUBJECT.PARENT_ACCOUNT_CODE IS '상위 계정코드';
COMMENT ON COLUMN ACCOUNT_SUBJECT.VALID_FROM_DATE IS '유효 시작일 (SCD2)';
COMMENT ON COLUMN ACCOUNT_SUBJECT.VALID_TO_DATE IS '유효 종료일 (SCD2)';
COMMENT ON COLUMN ACCOUNT_SUBJECT.IS_USED IS '사용여부';
COMMENT ON COLUMN ACCOUNT_SUBJECT.CREATE_DATE IS '생성일';
COMMENT ON COLUMN ACCOUNT_SUBJECT.UPDATE_DATE IS '수정일';
COMMENT ON COLUMN ACCOUNT_SUBJECT.AUDIT_USER IS '감사 사용자';

ALTER TABLE ACCOUNT_SUBJECT ADD CONSTRAINT FK_ACC_SUB_PARENT_ACC_CODE FOREIGN KEY (PARENT_ACCOUNT_CODE) REFERENCES ACCOUNT_SUBJECT (ACCOUNT_CODE);
CREATE INDEX IDX_ACC_SUB_PARENT_ACC_CODE ON ACCOUNT_SUBJECT (PARENT_ACCOUNT_CODE);
CREATE INDEX IDX_ACC_SUB_VALIDITY ON ACCOUNT_SUBJECT (VALID_FROM_DATE, VALID_TO_DATE);


