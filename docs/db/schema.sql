-- 7. JOURNAL_ENTRY (전표)
CREATE TABLE JOURNAL_ENTRY
(
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- 전표 ID (PK)
    JOURNAL_NO VARCHAR2(20) UNIQUE NOT NULL,                       -- 전표번호 (고유)
    JOURNAL_DATE DATE NOT NULL,                                    -- 전표일자
    TYPE VARCHAR2(20) NOT NULL,                                    -- 유형 (GENERAL, CLOSING)
    DEPT_CODE VARCHAR2(20),                                       -- 생성 부서코드 (FK)
    CREATED_BY VARCHAR2(50) NOT NULL,                              -- 생성자
    STATUS VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,                 -- 상태 (DRAFT, POSTED, CANCELED)
    TOTAL_DEBIT NUMBER(19, 2) NOT NULL,                            -- 차변 총액
    TOTAL_CREDIT NUMBER(19, 2) NOT NULL,                           -- 대변 총액
    CREATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,           -- 생성일
    UPDATE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,           -- 수정일
    AUDIT_USER VARCHAR2(50) DEFAULT 'SYSTEM' NOT NULL,             -- 감사 사용자

    CONSTRAINT FK_JE_DEPT_CODE FOREIGN KEY (DEPT_CODE) REFERENCES DEPARTMENT (DEPT_CODE),
    CONSTRAINT CHK_JE_DEBIT_CREDIT CHECK (TOTAL_DEBIT = TOTAL_CREDIT) -- 차변과 대변은 항상 일치해야 함
);

COMMENT ON TABLE JOURNAL_ENTRY IS '전표';
COMMENT ON COLUMN JOURNAL_ENTRY.ID IS '전표 ID';
COMMENT ON COLUMN JOURNAL_ENTRY.JOURNAL_NO IS '전표번호';
COMMENT ON COLUMN JOURNAL_ENTRY.JOURNAL_DATE IS '전표일자';
COMMENT ON COLUMN JOURNAL_ENTRY.TYPE IS '유형';
COMMENT ON COLUMN JOURNAL_ENTRY.DEPT_CODE IS '생성 부서코드';
COMMENT ON COLUMN JOURNAL_ENTRY.CREATED_BY IS '생성자';
COMMENT ON COLUMN JOURNAL_ENTRY.STATUS IS '상태';
COMMENT ON COLUMN JOURNAL_ENTRY.TOTAL_DEBIT IS '차변 총액';
COMMENT ON COLUMN JOURNAL_ENTRY.TOTAL_CREDIT IS '대변 총액';
COMMENT ON COLUMN JOURNAL_ENTRY.CREATE_DATE IS '생성일';
COMMENT ON COLUMN JOURNAL_ENTRY.UPDATE_DATE IS '수정일';
COMMENT ON COLUMN JOURNAL_ENTRY.AUDIT_USER IS '감사 사용자';

CREATE INDEX IDX_JE_JOURNAL_NO ON JOURNAL_ENTRY (JOURNAL_NO);
CREATE INDEX IDX_JE_JOURNAL_DATE ON JOURNAL_ENTRY (JOURNAL_DATE);
CREATE INDEX IDX_JE_DEPT_CODE ON JOURNAL_ENTRY (DEPT_CODE);


