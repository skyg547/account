(
    ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, -- 리스 계약 ID (PK)
    CONTRACT_NO VARCHAR2(20) UNIQUE NOT NULL,                      -- 계약번호 (고유)
